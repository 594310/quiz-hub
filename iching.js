const m8=n=>{const r=n%8;return r===0?8:r}, m6=n=>{const r=n%6;return r===0?6:r};
function trigram(bits){return TBITS[bits.map(b=>b?1:0).join('')]}
function hexFrom(yangs){return HMAP[trigram(yangs.slice(3))+trigram(yangs.slice(0,3))]}
function fullName(h){return h[1]===h[2]?(h[0]==='乾'?'乾為天':h[0]+'為'+TNAT[h[1]]):TNAT[h[1]]+TNAT[h[2]]+h[0]}
// 梅花易數（時間起卦）：yb=年支數(子1…亥12)、m=農曆月、d=農曆日、hb=時辰數(子1…亥12)
function plumCast(yb,m,d,hb){
  const s3=yb+m+d, s4=s3+hb, up=m8(s3), low=m8(s4), dong=m6(s4);
  const yang=[...bitsOf(XT[low]),...bitsOf(XT[up])].map(Boolean);
  const ben=hexFrom(yang), chg=hexFrom(yang.map((y,i)=>i===dong-1?!y:y));
  return {s3,s4,up,low,dong,ben,chg,score:Math.round(ben[5]*0.55+chg[5]*0.45),benName:fullName(ben),chgName:fullName(chg)};
}
